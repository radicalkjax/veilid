#!/bin/bash
# Census driver: turn an ast-grep scan into a stable, diffable inventory.
#
#   _census.sh generate <sgconfig> <outfile>
#
# Kept to a CLI contract rather than a sourced library so the same interface can be
# reimplemented in another language, or copied into a repo that has no veilid checkout
# beside it, without either caller changing.
#
# The inventory is COUNTS per (rule, file), never line numbers: a reformat moves every
# line but changes no count, which is the whole reason the inventory is shaped this way.

set -eo pipefail

# 2, not 1: the caller distinguishes "the tool broke" from "the census drifted"
fail() {
    echo "census: $*" >&2
    exit 2
}

[ $# -eq 3 ] || fail "usage: $0 generate <sgconfig> <outfile>"
[ "$1" = "generate" ] || fail "unknown subcommand: $1"
config="$2"
out="$3"

[ -f "$config" ] || fail "no such config: $config"
command -v ast-grep > /dev/null 2>&1 || fail "ast-grep is not on PATH (see dev-setup)"

scratch="$(mktemp -d)"
trap 'rm -rf "$scratch"' EXIT

# ast-grep exits 1 when it finds error-severity matches, which is the normal case here,
# so its status says nothing about whether the scan itself worked. Judge that on whether
# the output parses as JSON instead.
ast-grep scan --config "$config" --json=compact > "$scratch/findings.json" 2>"$scratch/err" || true

python3 - "$scratch/findings.json" "$out" <<'PY'
import json, sys, collections
src, out = sys.argv[1], sys.argv[2]
raw = open(src, encoding="utf-8").read()
try:
    findings = json.loads(raw) if raw.strip() else []
except json.JSONDecodeError:
    sys.exit(1)
counts = collections.Counter((f["ruleId"], f["file"]) for f in findings)
with open(out, "w", encoding="utf-8") as fh:
    fh.write("# Generated by scripts/update_census.sh. Do not edit by hand.\n")
    fh.write("# <count> <rule> <file>\n")
    for (rule, path), n in sorted(counts.items()):
        fh.write(f"{n} {rule} {path}\n")
PY
rc=$?
if [ $rc -ne 0 ]; then
    echo "census: ast-grep produced no parseable output. Its stderr was:" >&2
    cat "$scratch/err" >&2
    exit 2
fi
